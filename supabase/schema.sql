-- ====================================================
-- Bluehouse Cafe QR Order - Supabase Database Schema
-- คัดลอกโค้ดทั้งหมดนี้ไปวางในเมนู SQL Editor ของ Supabase แล้วกด RUN
-- ====================================================

-- 1. ตาราง categories (หมวดหมู่สินค้า)
CREATE TABLE IF NOT EXISTS public.categories (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    sort_order INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. ตาราง products (รายการเมนูอาหาร & สถานะสต็อกแบบรวมศูนย์)
CREATE TABLE IF NOT EXISTS public.products (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    category TEXT NOT NULL,
    image TEXT NOT NULL,
    tag TEXT,
    description TEXT,
    is_out_of_stock BOOLEAN NOT NULL DEFAULT false,
    has_sweetness BOOLEAN NOT NULL DEFAULT true,
    has_temperature BOOLEAN NOT NULL DEFAULT true,
    temperature_options JSONB DEFAULT '["hot", "iced", "frappe"]'::jsonb,
    temperature_diff JSONB DEFAULT '{"hot": 0, "iced": 5, "frappe": 15}'::jsonb,
    allow_toppings BOOLEAN NOT NULL DEFAULT true,
    sort_order INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. ตาราง orders (รายการสั่งอาหารของแต่ละโต๊ะ)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no TEXT NOT NULL UNIQUE,
    table_no INTEGER NOT NULL,
    customer_name TEXT,
    note TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ====================================================
-- 4. เปิดใช้งาน Row Level Security (RLS)
-- ====================================================
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- ====================================================
-- 5. กำหนดสิทธิ์ความปลอดภัย (Security Hardened Policies)
-- ====================================================

-- สิทธิ์ Categories & Products:
-- ทุกคนสามารถอ่านเมนูได้ (หน้าร้าน & ลูกค้า)
DROP POLICY IF EXISTS "Public can read categories" ON public.categories;
CREATE POLICY "Public can read categories"
    ON public.categories FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public can read products" ON public.products;
CREATE POLICY "Public can read products"
    ON public.products FOR SELECT
    USING (true);

-- อนุญาตให้อัปเดตและจัดการเมนูเฉพาะผู้ที่ล็อกอินพนักงาน (Authenticated Users)
-- หรือผ่าน Service Role / Admin Backend
DROP POLICY IF EXISTS "Staff can manage categories" ON public.categories;
CREATE POLICY "Staff can manage categories"
    ON public.categories FOR ALL
    USING (auth.role() = 'authenticated')
    WITH CHECK (auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Staff can manage products" ON public.products;
CREATE POLICY "Staff can manage products"
    ON public.products FOR ALL
    USING (auth.role() = 'authenticated')
    WITH CHECK (auth.role() = 'authenticated');

-- สิทธิ์ Orders:
-- ลูกค้าหน้าร้านสามารถส่งออเดอร์ใหม่ได้
DROP POLICY IF EXISTS "Public can insert orders" ON public.orders;
CREATE POLICY "Public can insert orders"
    ON public.orders FOR INSERT
    WITH CHECK (true);

-- ลูกค้าหน้าร้านและพนักงานสามารถอ่านออเดอร์ได้
DROP POLICY IF EXISTS "Public can read orders" ON public.orders;
CREATE POLICY "Public can read orders"
    ON public.orders FOR SELECT
    USING (true);

-- [SECURITY FIX] ปิดกั้นไม่ให้บุคคลทั่วไปลบหรือแก้ไขข้อมูลออเดอร์
-- อนุญาตเฉพาะพนักงานที่ล็อกอิน หรือผ่าน Backend Server
DROP POLICY IF EXISTS "Staff can update orders" ON public.orders;
CREATE POLICY "Staff can update orders"
    ON public.orders FOR UPDATE
    USING (auth.role() = 'authenticated')
    WITH CHECK (auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Staff can delete orders" ON public.orders;
CREATE POLICY "Staff can delete orders"
    ON public.orders FOR DELETE
    USING (auth.role() = 'authenticated');

-- ====================================================
-- 6. เปิดระบบ Realtime (สำหรับ Kitchen KDS & ลูกค้า)
-- ====================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'orders'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'products'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
  END IF;
END $$;

