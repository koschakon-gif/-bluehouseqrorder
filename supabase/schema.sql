-- Bluehouse QR Order - Supabase Schema
-- Run this script in the Supabase SQL Editor

-- 1. Create orders table
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no TEXT NOT NULL UNIQUE,
    table_no INTEGER,
    customer_name TEXT,
    note TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Customers can read and create orders
CREATE POLICY "Public can insert orders"
    ON public.orders FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Public can read orders"
    ON public.orders FOR SELECT
    USING (true);

-- 4. Policy: Authenticated staff can update and delete orders
CREATE POLICY "Staff can update orders"
    ON public.orders FOR UPDATE
    USING (true);

CREATE POLICY "Staff can delete orders"
    ON public.orders FOR DELETE
    USING (true);

-- 5. Enable Realtime on orders table
ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
